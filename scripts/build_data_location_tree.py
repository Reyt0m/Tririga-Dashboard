def split(s):
    out = []; buf = ''; d = 0
    for ch in s:
        if ch in '（(': d += 1
        if ch in '）)': d -= 1
        if ch in '、＋' and d == 0:
            out.append(buf.strip()); buf = ''
        else:
            buf += ch
    out.append(buf.strip())
    return [x for x in out if x]


